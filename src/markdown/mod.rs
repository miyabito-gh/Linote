//! Markdown から HTML への変換（タスク G の担当。`src/markdown/` 配下）。
//!
//! 責務: `pulldown-cmark` による解析と HTML の生成（表、チェックリスト、コードブロック）、
//! プレビュー用のスタイル（明暗テーマ）、埋め込み HTML・スクリプト・外部リソースの無効化。
//! GUI に依存せず、`windows` crate を使わない。表示は `ui::preview`（タスク H）。
//!
//! 取り決め:
//! - 入力は本文の写し（UTF-8）と [`crate::core::DocStamp`]。変換は
//!   [`crate::core::WorkerPool`] で行い、結果に同じ印を付けて返す。UI は反映前に照合し、
//!   編集や閉鎖で古くなった結果を捨てる。
//! - 変換は入力が落ち着いてから始める（待ち時間の管理は UI 側）。変換中に次の版が
//!   来たら [`crate::core::CancelToken`] で中止する。
//! - 埋め込み HTML は文字として表示する（エスケープ）。スクリプト、イベント属性、
//!   外部 URL の自動読み込み（画像を含む）を出力しない。出力する HTML には
//!   外部リソースを禁じる Content-Security-Policy を付ける。
//! - 右ペインと別ウィンドウは同じ変換結果とスタイルを使う。
//! - 初めてプレビューを開くまで何も初期化しない。
