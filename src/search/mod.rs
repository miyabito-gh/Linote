//! 検索・置換・Grep の中核（タスク K の担当。`src/search/` 配下）。
//!
//! 責務: 文字列検索と正規表現検索（Rust `regex` 構文）、置換文字列の展開、フォルダーを
//! またぐ Grep、結果の構造化。GUI に依存せず、`windows` crate を使わない。
//! 検索欄・Grep 結果の画面は `ui::find`（同じくタスク K）。
//!
//! 取り決め:
//! - 文書内の検索は [`crate::document::TextSource`] に対して行う（通常編集は UI が渡す
//!   範囲の写し、巨大モードは `bigfile` の実装）。位置は UTF-8 のバイト位置
//!   （[`crate::document::TextRange`]）。
//! - 長い処理は [`crate::core::TaskContext`] を受け取る。中止に応じ、進捗を報告し、
//!   [`crate::core::Limits`] を守る。結果は [`crate::core::Outcome`] で返し、上限・中止で
//!   打ち切ったことが分かるようにする。
//! - 無効なパターンは [`crate::core::Error::InvalidArgument`]（検索欄に表示する）。
//! - Grep は通常編集と同じ文字コード（`text` モジュール）を扱う。結果はファイル名・
//!   行番号・該当箇所を持つ構造体にし、将来の MCP でそのまま返せる形（JSON にできる形）
//!   にする。
//! - 巨大モードの正規表現検索は行単位。長大な 1 行でもメモリ使用量に上限を設ける。
//! - 文書に対する検索結果には [`crate::core::DocStamp`] を付け、UI は反映前に照合する。
//! - 初めて使うまで初期化しない（正規表現の構築、スレッドの起動を起動経路に置かない）。
